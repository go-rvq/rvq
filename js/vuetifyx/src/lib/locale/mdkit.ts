export function mdkitWords(t: (key: string) => string): Record<string, Record<string, string>> {
  const out: Record<string, Record<string, string>> = {}
  for (const [editor, keys] of Object.entries(mdkitKeys)) {
    out[editor] = {}
    for (const [word, key] of Object.entries(keys)) out[editor][word] = t(key)
  }
  return out
}
