// messagesFor: the texts of a locale (pt, pt_BR, pt-BR: Portuguese), English
// else.
export function messagesFor(locale: string | undefined | null): Messages {
  const l = (locale || '').toLowerCase()
  return l.startsWith('pt') ? ptMessages : defaultMessages
}

// pageLocale: the page's (its vue-i18n, its <html lang>), else the browser's.
export function pageLocale(app?: any): string {
  const i18n = app?.config?.globalProperties?.$i18n
  const loc = i18n?.locale?.value ?? i18n?.locale
  if (typeof loc === 'string' && loc) return loc
  if (typeof document !== 'undefined' && document.documentElement.lang) return document.documentElement.lang
  return typeof navigator !== 'undefined' ? navigator.language : 'en'
}
