#!/bin/sh
# The bundle of mdkit for a page: dist/mdkit.js (window.RvqMdKit) — and
# dist/page.js, what a page that shows a text draws —, embedded
# in the binary (rvq js.MdKit; x/ui/mdkit JSComponentsPack). Vue and Vuetify
# are the page's, not in it. Run when src/ or its dependencies change:
#   sh js/mdkit/build.sh
set -e
cd "$(dirname "$0")"
# EasyMDE's styles as a module of a string: read by bun and by vite (the
# admin's vuetifyx) alike
mkdir -p src/vendor
node -e 'const fs=require("fs");const p=require.resolve("easymde/dist/easymde.min.css");fs.writeFileSync("src/vendor/easymde-css.js","// EasyMDE'"'"'s styles (generated by build.sh from easymde/dist/easymde.min.css)\nexport default "+JSON.stringify(fs.readFileSync(p,"utf8"))+"\n")'
bun build src/bundle.js --minify --target=browser --format=iife --outfile=dist/mdkit.js
# a page that shows a text, no editor (its link cards, formulas, diagrams):
# dist/page.js
bun build src/page.js --minify --target=browser --format=iife --outfile=dist/page.js
# the Prism of a page that shows a text, highlighting its code (code.js):
# served as rvq's vendor (js/vendor/prism, vendor.Prism)
bun build src/prism/bundle.js --minify --target=browser --format=iife --outfile=../vendor/prism/1.30.0/prism.min.js
# the CodeMirror of the code blocks of the rich text editor
# (code-block-tiptap.js): served as rvq's vendor (js/vendor/codemirror,
# vendor.CodeMirror)
bun src/codemirror/build.js
